"""CargoSnapshotSuite suite adapter."""

import os

from ..base import ReproductionSuite
from ..utils.compiled import _patched_files, _run
from ..utils.logging import log
from ..utils.managed import _CARGO_RESULT_RE, _CARGO_STATUS, cargo_target_of


class CargoSnapshotSuite(ReproductionSuite):
    """A cargo workspace whose tests are a **fixture corpus plus recorded output**.

    :class:`CargoSuite` addresses cargo's *integration* test targets — a file under
    `<crate>/tests/`, run by name. That is the wrong handle for a tool whose tests are
    data. ruff is the shape: a rule owns a fixture under
    `crates/<crate>/resources/test/fixtures/<group>/X001.py` and an ``insta`` snapshot of
    the exact diagnostics it must produce, and the case that ties them together is an
    inline `#[cfg(test)] mod tests` in `src/rules/<group>/mod.rs`, generated by a
    `#[test_case(...)]` attribute per fixture. So a fix's whole test change can be a
    ``.py`` and a ``.snap`` — neither of which is a cargo target, and neither of which
    names a test function.

    What the corpus path *does* name reliably is the **module** the cases live in:
    `resources/test/fixtures/<group>/…` and `src/rules/<group>/snapshots/…` both give
    `<group>`, and libtest's filter is a substring match over the full path of a test, so
    `rules::<group>::` selects exactly that rule group's cases and nothing else. Selection
    is therefore at *group* granularity rather than per case — the alternative would be to
    reconstruct the name `test_case` generates from its arguments, which is a guess about
    a macro's internals rather than a fact about the tree.

    Because it is coarser than a single case, an unrelated failure inside the same group
    would land in the subtask's verdict. That is a real cost and the reason this is not the
    default: it is acceptable only where the suite is green at the anchor, which for a
    release tag of a snapshot-tested linter it is.

    ``groups`` maps a path prefix to the crate and module prefix it selects. Anything under
    `<crate>/tests/` still resolves the ordinary way, as a cargo integration target.
    """

    no_targets = "test patch touched no fixture, snapshot or integration test"

    def __init__(self, groups=(), cargo_args=(), lib_only=True):
        # Each entry: {"prefix": …, "crate": …, "module": …} — `module` is a format string
        # taking the group name captured from the path segment after `prefix`.
        self.groups = [dict(g) for g in groups]
        self.cargo_args = list(cargo_args)
        self.lib_only = lib_only

    # --- resolving the diff --------------------------------------------------

    def _group_of(self, path):
        for g in self.groups:
            prefix = g["prefix"].rstrip("/") + "/"
            if not path.startswith(prefix):
                continue
            rest = path[len(prefix) :].split("/")
            if not rest or not rest[0]:
                continue
            return g["crate"], g["module"].format(group=rest[0])
        return None

    def targets(self, diff, env=None):
        """``([(crate, filter | None, target | None)], [readable ids])``.

        A filter selects a module inside the crate's lib tests; a target is an ordinary
        cargo integration test. Exactly one of the two is set per entry."""
        del env
        found = []
        for path in _patched_files(diff):
            hit = self._group_of(path)
            if hit is not None:
                entry = (hit[0], hit[1], None)
            else:
                t = cargo_target_of(path)
                if t is None:
                    continue
                # `crates/ruff_python_formatter/tests/snapshots/…` is the recorded output
                # of the `fixtures` target, not a target of its own.
                crate, target = t
                if target == "snapshots":
                    continue
                entry = (crate, None, target)
            if entry not in found:
                found.append(entry)
        names = [f or (t or "") for _c, f, t in found]
        return sorted(found), sorted(set(n for n in names if n))

    # --- running --------------------------------------------------------------

    def run_tests(self, env, repo, files, names, timeout, jobs):
        del jobs
        outcomes = {}
        error = False
        if files is None:
            files = [(None, None, None)]
        for crate, module, target in files:
            cmd = ["cargo", "test"]
            if crate:
                cmd += ["-p", os.path.basename(crate)]
            if target is not None:
                cmd += ["--test", target]
            elif self.lib_only:
                cmd += ["--lib"]
            cmd += self.cargo_args
            if module is not None:
                cmd += ["--", module]
            r = _run(env, cmd, timeout=timeout, cwd=repo)
            if r is None:
                log("cargo test TIMEOUT after %ds (%s)" % (timeout, module or target))
                return {}, 0, False, True
            log("cargo test %s rc=%d" % (module or target, r.returncode))
            log(r.stdout[-2000:])
            seen = 0
            for line in r.stdout.splitlines():
                m = _CARGO_RESULT_RE.match(line)
                if m:
                    seen += 1
                    outcomes[m.group(1)] = _CARGO_STATUS[m.group(2)]
            # rc != 0 with no case reported means it never got to running: a compile
            # error, or a panic that took the harness with it.
            if r.returncode != 0 and seen == 0:
                error = True
            # A filter that matches nothing is not a pass either — the patch names a
            # module the crate does not have, so nothing was graded.
            if seen == 0 and r.returncode == 0:
                error = True
        n = len([o for o in outcomes.values() if o != "skipped"])
        return outcomes, n, error, False
